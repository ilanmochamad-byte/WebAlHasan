    santri_id INT NOT NULL,
    tahun_ajaran_id INT NOT NULL,
    pembimbing_id BIGINT UNSIGNED NULL,
    pembimbing_assignment_id BIGINT UNSIGNED NULL,
    katalog_id BIGINT UNSIGNED NULL,
    waktu_kejadian DATETIME NOT NULL,
