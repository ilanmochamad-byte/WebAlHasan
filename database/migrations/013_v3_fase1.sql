    UNIQUE KEY pelanggaran_retry (created_by,idempotency_key),
    UNIQUE KEY pelanggaran_fingerprint (santri_id,tahun_ajaran_id,fingerprint),
    INDEX pelanggaran_riwayat (santri_id,tahun_ajaran_id,waktu_kejadian),
    CHECK (poin_snapshot >= 0),
    CHECK (data_warisan IN (0,1)),
    created_by BIGINT UNSIGNED NULL,
