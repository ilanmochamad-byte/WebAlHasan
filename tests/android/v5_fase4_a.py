"""Uji Android emulator PRD V5 Fase 4 — petugas (catat, ketukan ganda, koreksi, terbit). Argumen: penanda unik. Prasyarat di docs/phase-v5-4/README.md."""
import os, subprocess, time, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from adbui import *
WEB=os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
def sql(q): return subprocess.run(['php', WEB+'/tests/v5_phase4_sql.php', q], capture_output=True, text=True, env={'DB_NAME':'test_v5_f4_app_test','PATH':'/opt/homebrew/bin:/usr/bin:/bin'}).stdout.strip()
T = sys.argv[1]
OUT = os.environ.get('OUT_DIR', '/tmp/v5f4-android')
os.makedirs(OUT, exist_ok=True)
def masuk(u):
    isi('Masukkan username', u); isi('Masukkan password', 'Sandbox#123'); tap('Masuk', exact=True); time.sleep(4)
hasil=[]
def ok(v,l): print(('[lulus] ' if v else '[gagal] ')+l, flush=True); hasil.append(v)
if find('Masukkan username')[0]: masuk('sbx_v5_petugas_f')
tap('Kesehatan', exact=True)
tap('Catat kunjungan', exact=True)
isi('Cari nama atau NIS santri aktif', 'V5S0201')
tap('Cari santri', exact=True)
tap('· V5S0201')
isi('Keluhan (wajib)', f'{T}-KELUHAN')
isi('Catatan klinis', f'{T}-CATATAN')
tap('Tambah obat', exact=True)
isi('Obat 1: nama', f'{T}-OBAT1', exact=True)
tap('Tambah rujukan', exact=True)
isi('Rujukan 1: tujuan', f'{T}-RUJUKAN', exact=True)
layar(f'{OUT}/android-petugas-catat.png')
p = posisi('Simpan sebagai tercatat', exact=True)
sh('shell', 'input', 'tap', str(p[0]), str(p[1])); sh('shell', 'input', 'tap', str(p[0]), str(p[1]))
time.sleep(5)
n = sql(f"SELECT COUNT(*) FROM kesehatan_kunjungan WHERE keluhan='{T}-KELUHAN'")
ok(n == '1', f'Android: ketukan ganda Simpan → tepat satu kunjungan (baris={n})')
wait(f'{T}-OBAT1')
ok(True, 'Android: detail kunjungan memuat obat dari server')
layar(f'{OUT}/android-petugas-detail.png')
kid = sql(f"SELECT id FROM kesehatan_kunjungan WHERE keluhan='{T}-KELUHAN'")
ok(sql(f"SELECT COUNT(*) FROM kesehatan_obat WHERE kunjungan_id={kid}") == '1' and sql(f"SELECT COUNT(*) FROM kesehatan_rujukan WHERE kunjungan_id={kid}") == '1', 'Android: obat dan rujukan tersimpan pada kunjungan yang sama')
tap('Koreksi catatan', exact=True)
isi('Tindakan', f'{T}-TINDAKAN', exact=True)
isi('Alasan koreksi (wajib)', 'Koreksi dari Android', exact=True)
tap('Simpan koreksi', exact=True); time.sleep(4)
ok(sql(f"SELECT versi FROM kesehatan_kunjungan WHERE id={kid}") == '2', 'Android: koreksi beralasan → versi 2')
tap('Ringkasan untuk wali', exact=True)
isi('Ringkasan (wajib, minimal 10 karakter)', f'{T}-RINGKASAN-wali', exact=True)
tap('Lihat pratinjau', exact=True)
wait('Pratinjau — persis seperti dilihat wali')
tap('Saya sudah memeriksa pratinjau dan ingin menerbitkannya')
p = posisi('Terbitkan', exact=True)
sh('shell', 'input', 'tap', str(p[0]), str(p[1])); sh('shell', 'input', 'tap', str(p[0]), str(p[1]))
wait('terbit. Notifikasi')
rid = sql(f"SELECT id FROM kesehatan_ringkasan WHERE kunjungan_id={kid}")
ok(sql(f"SELECT COUNT(*) FROM kesehatan_ringkasan_peristiwa WHERE ringkasan_id={rid}") == '1', 'Android: ketukan ganda Terbitkan → satu peristiwa')
layar(f'{OUT}/android-petugas-terbit.png')
open(f'{OUT}/ids.txt','w').write(f'{kid} {rid}\n')
print('KID', kid, 'RID', rid, 'GAGAL', hasil.count(False))
